#!/bin/bash
set -e

psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" <<-EOSQL
    CREATE ROLE $DRILL_ADMIN_DB_USER WITH
        LOGIN
        PASSWORD '$DRILL_ADMIN_DB_PASSWORD'
        NOSUPERUSER
        NOCREATEDB
        NOCREATEROLE
        NOINHERIT;
    GRANT CONNECT ON DATABASE ${POSTGRES_DB} TO $DRILL_ADMIN_DB_USER;
    GRANT CREATE ON DATABASE ${POSTGRES_DB} TO $DRILL_ADMIN_DB_USER;
    GRANT CONNECT ON DATABASE "${DRILL_METRICS_DB_NAME}" TO $DRILL_ADMIN_DB_USER;
    GRANT CREATE ON DATABASE "${DRILL_METRICS_DB_NAME}" TO $DRILL_ADMIN_DB_USER;
EOSQL
